"""Run: python browser_test.py; Chromium document injection (file navigation policy blocked)."""
import json
from pathlib import Path
from playwright.sync_api import sync_playwright

ROOT=Path(__file__).parent
assertions=[]
def check(name,cond):
    assertions.append((name,bool(cond)))
    if not cond: raise AssertionError(name)

with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox'])
    context=browser.new_context(viewport={'width':1280,'height':900},accept_downloads=True)
    page=context.new_page()
    errors=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    html=(ROOT/'index.html').read_text(encoding='utf-8')
    for name in ('engine.js','app.js'):
        html=html.replace(f'<script src="{name}"></script>',
             '<script>'+ (ROOT/name).read_text(encoding='utf-8').replace('</script>',r'<\/script>') + '</script>')
    # In this sandbox, file:// and localhost navigation are blocked. Use an in-memory store.
    html=html.replace('<script>', '<script>window.__fakeStorage=window.__fakeStorage||{};Object.defineProperty(window,"localStorage",{value:{getItem(k){return window.__fakeStorage[k]||null},setItem(k,v){window.__fakeStorage[k]=v}}});</script><script>',1)
    page.set_content(html,wait_until='load')
    check('initial page title','端材バンク' in page.title())
    check('initial stock 2 rows',page.locator('#stock-list .list-row').count()==2)
    check('initial cuts 3 rows',page.locator('#cut-list .list-row').count()==3)
    check('initial plan is computed',page.locator('.plan-bar').count()>0)
    check('initial complete',page.locator('#status').inner_text()=='全件割付')
    page.screenshot(path=str(ROOT/'desktop.png'),full_page=True)
    page.locator('#stock-label').fill('角材テスト')
    page.locator('#stock-length').fill('1200')
    page.locator('#stock-qty').fill('2')
    page.locator('#stock-form button[type=submit]').click()
    check('add stock',page.locator('#stock-list .list-row').count()==3)
    page.locator('#cut-label').fill('棚板の枠')
    page.locator('#cut-length').fill('400')
    page.locator('#cut-qty').fill('2')
    page.locator('#cut-form button[type=submit]').click()
    check('add cut',page.locator('#cut-list .list-row').count()==4)
    page.locator('#cut-list button[data-action="edit"]').last.click()
    check('edit mode',page.locator('#cut-submit').inner_text()=='変更を保存')
    page.locator('#cut-length').fill('425')
    page.locator('#cut-submit').click()
    check('edit saved','425 mm' in page.locator('#cut-list').inner_text())
    page.locator('#cut-list button[data-action="remove"]').last.click()
    check('remove cut',page.locator('#cut-list .list-row').count()==3)
    page.locator('#kerf').fill('7')
    page.locator('#kerf').dispatch_event('change')
    check('changing kerf updates plan','刃幅 7mm' in page.locator('#plan-note').inner_text())
    page.locator('#stock-label').fill('巨大規格')
    page.locator('#stock-length').fill('9999')
    page.locator('#stock-qty').fill('1')
    page.locator('#stock-submit').click()
    check('four stock rows',page.locator('#stock-list .list-row').count()==4)
    with page.expect_download() as info:page.locator('#download-json').click()
    check('backup name',info.value.suggested_filename.endswith('.json'))
    data=page.evaluate("JSON.stringify(window.__fakeStorage)")
    page.set_content(html,wait_until="load")
    page.evaluate("v=>{Object.assign(window.__fakeStorage,JSON.parse(v));}",data)
    # Re-render with the saved snapshot, simulating a fresh visit with persisted browser state.
    page.set_content(html,wait_until="load")
    check('reload persists stock',page.locator('#stock-list .list-row').count()==4)
    check('reload persists settings',page.locator('#kerf').input_value()=='7')
    with page.expect_download() as info:page.locator('#export-csv').click()
    check('csv download',info.value.suggested_filename.endswith('.csv'))
    page.locator('#cut-list button[data-action="remove"]').last.click()
    page.locator('#cut-list button[data-action="remove"]').last.click()
    page.locator('#cut-list button[data-action="remove"]').last.click()
    check('no cuts shows disabled commit',page.locator('#confirm-cut').is_disabled())
    page.locator('#cut-label').fill('細い桟')
    page.locator('#cut-length').fill('150')
    page.locator('#cut-qty').fill('1')
    page.locator('#cut-submit').click()
    check('one cut fitted',page.locator('#status').inner_text()=='全件割付')
    page.on('dialog',lambda d:d.accept())
    before=page.locator('#stock-list .list-row').count()
    page.locator('#confirm-cut').click()
    check('commit clears cuts',page.locator('#cut-list .list-row').count()==0)
    check('commit records receipt','前回の確定' in page.locator('#receipt').inner_text())
    check('undo enabled',page.locator('#undo').is_enabled())
    page.locator('#undo').click()
    check('undo restores cuts',page.locator('#cut-list .list-row').count()==1)
    page.set_viewport_size({'width':390,'height':844})
    page.screenshot(path=str(ROOT/'mobile.png'),full_page=True)
    check('mobile not overflowing',page.evaluate('document.documentElement.scrollWidth <= window.innerWidth + 1'))
    page.set_viewport_size({'width':1280,'height':900})
    check('no JS exceptions',not errors)
    browser.close()
print('\n'.join(('PASS ' if ok else 'FAIL ')+name for name,ok in assertions))
print(f'BROWSER: {sum(v for _,v in assertions)}/{len(assertions)} passed')
