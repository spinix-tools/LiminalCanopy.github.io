"""Chromium UI tests. Uses real HTML/CSS/JS injected into one page because file: navigations are blocked here."""
from pathlib import Path
from playwright.sync_api import sync_playwright
BASE=Path(__file__).parent
html=(BASE/'index.html').read_text().replace('<link rel="stylesheet" href="style.css">','<style>'+(BASE/'style.css').read_text()+'</style>').replace('<script src="engine.js"></script>','<script>'+(BASE/'engine.js').read_text()+'</script>').replace('<script src="app.js"></script>','<script>'+(BASE/'app.js').read_text()+'</script>')
checks=[]
def check(label,cond):
    checks.append((label,bool(cond)))
    if not cond: raise AssertionError(label)
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox'])
    page=browser.new_page(viewport={'width':1440,'height':900},accept_downloads=True)
    errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
    page.set_content(html,wait_until='load');
    check('title', 'とおるかな' in page.title())
    check('default sample name',page.locator('#name').input_value()=='本棚')
    check('default report',page.locator('#status-badge').inner_text()=='未探索')
    check('svg corridor drawn',page.locator('#plan polygon').count()>0)
    check('baseline width',page.locator('#stat-width').inner_text()=='105 cm')
    page.locator('#search').click()
    check('route found',page.locator('#status-badge').inner_text()=='候補あり')
    check('nontrivial steps',int(page.locator('#stat-steps').inner_text())>20)
    check('trace polyline',page.locator('#plan polyline').count()==2)
    check('forward enabled',page.locator('#next').is_enabled())
    page.locator('#next').click()
    check('next step',page.locator('#step-count').inner_text().startswith('1 /'))
    page.locator('#prev').click()
    check('previous step',page.locator('#step-count').inner_text().startswith('0 /'))
    page.locator('#timeline').fill(page.locator('#timeline').get_attribute('max'))
    check('scrub to finish',page.locator('#step-label').inner_text()=='経路の終点')
    page.locator('#timeline').fill('0')
    page.locator('#play').click();page.wait_for_timeout(400)
    check('playback advancing',int(page.locator('#timeline').input_value())>0)
    page.locator('#play').click()
    page.locator('#preset').select_option('sofa')
    check('sofa dimensions loaded',page.locator('#length').input_value()=='180')
    page.locator('#search').click()
    check('sofa successful route',page.locator('#status-badge').inner_text()=='候補あり')
    page.locator('#preset').select_option('appliance')
    check('refrigerator dims loaded',page.locator('#depth').input_value()=='72')
    page.locator('#search').click()
    check('refrigerator successful route',page.locator('#status-badge').inner_text()=='候補あり')
    page.locator('#height').fill('400');page.locator('#height').dispatch_event('change')
    check('validation error appears',page.locator('#status-badge').inner_text()=='入力エラー')
    page.locator('#reset').click()
    check('reset original preset',page.locator('#length').input_value()=='120')
    page.locator('#restart').click()
    check('restart path clears',page.locator('#stat-steps').inner_text()=='—')
    page.locator('[data-move="0,-1"]').click()
    check('manual makes a step',page.locator('#step-count').inner_text().startswith('1 / 1'))
    page.locator('#restart').click()
    page.locator('[data-rotate="15"]').click()
    check('manual rotate works or collision indicated',page.locator('#stat-steps').inner_text()=='1' or '壁に接触' in page.locator('#issues').inner_text())
    page.locator('#search').click()
    with page.expect_download() as d: page.locator('#save-svg').click()
    check('SVG export',d.value.suggested_filename=='toorukana-plan.svg')
    with page.expect_download() as d: page.locator('#save-csv').click()
    check('CSV export',d.value.suggested_filename=='toorukana-route.csv')
    with page.expect_download() as d: page.locator('#save-json').click()
    check('JSON export',d.value.suggested_filename=='toorukana-settings.json')
    page.locator('#json-input').set_input_files({'name':'test.json','mimeType':'application/json','buffer':b'{"params":{"name":"custom","length":90,"depth":35,"height":90,"vertical":130,"horizontal":130,"leg":350,"clearance":4,"ceiling":220,"step":10}}'})
    page.wait_for_function("document.querySelector('#length').value === '90'", timeout=5000)
    check('JSON import updates length',page.locator('#length').input_value()=='90')
    page.locator('#json-input').set_input_files({'name':'bad.json','mimeType':'application/json','buffer':b'{"params":{"height":9000}}'})
    page.wait_for_function("document.querySelector('#issues').textContent.includes('読込エラー')",timeout=5000)
    check('invalid import error', '読込エラー' in page.locator('#issues').inner_text())
    check('no runtime exception',len(errors)==0)
    page.locator('#reset').click();page.locator('#search').click()
    page.screenshot(path=str(BASE/'desktop.png'),full_page=True)
    mobile=browser.new_page(viewport={'width':390,'height':844},device_scale_factor=1,accept_downloads=True)
    mobile.set_content(html,wait_until='load');mobile.locator('#search').click()
    check('mobile successfully calculates',mobile.locator('#status-badge').inner_text()=='候補あり')
    check('mobile no horizontal overflow',mobile.evaluate('document.documentElement.scrollWidth <= window.innerWidth+1'))
    mobile.screenshot(path=str(BASE/'mobile.png'),full_page=True)
    browser.close()
print(f'Chromium: {sum(ok for _,ok in checks)}/{len(checks)} PASS')
for name,passed in checks: print(('PASS' if passed else 'FAIL'),name)
