"""End-to-end smoke and regression checks using system Chromium and Playwright."""
from pathlib import Path
from playwright.sync_api import sync_playwright
import json

ROOT=Path(__file__).parent
HTML=(ROOT/'index.html').read_text().replace('<script src="engine.js"></script><script src="app.js"></script>', '')
ENGINE=(ROOT/'engine.js').read_text()
APP=(ROOT/'app.js').read_text()
def load_page(page, saved=None):
    page.set_content(HTML,wait_until='load')
    js = """(() => { const mem = new Map(Object.entries(%s));
    Object.defineProperty(window, 'localStorage', {configurable:true,value:{
    getItem:(k)=>mem.has(k)?mem.get(k):null,
    setItem:(k,v)=>mem.set(k,String(v)), removeItem:(k)=>mem.delete(k),
    clear:()=>mem.clear()}}); })();""" % json.dumps(saved or {}, ensure_ascii=False)
    page.add_script_tag(content=js)
    page.add_script_tag(content=ENGINE)
    page.add_script_tag(content=APP)


def run():
    checks=[]
    def check(label, actual):
        if not actual: raise AssertionError(label)
        checks.append(label)
    with sync_playwright() as p:
        browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox','--disable-dev-shm-usage'])
        context=browser.new_context(viewport={'width':1440,'height':950},accept_downloads=True)
        page=context.new_page()
        errors=[]
        page.on('pageerror',lambda e:errors.append(str(e)))
        load_page(page)
        check('page title', '寸感' in page.title())
        check('initial four cards',page.locator('.candidate').count()==4)
        check('initial count indicator',page.locator('#count').inner_text()=='4')
        check('reference length initial',page.locator('#ref-length').input_value()=='68')
        check('top metric label',page.locator('label[for="ref-width"]').inner_text()=='身幅')
        check('initial reference value',page.locator('#comparisonLabel').inner_text().startswith('着慣れたシャツ'))
        check('best is B medium',page.locator('#best').inner_text()=='M')
        check('first card B',page.locator('.candidate').first.locator('.cname').inner_text().startswith('候補B'))
        page.locator('#ref-width').fill('56')
        page.locator('#ref-width').dispatch_event('change')
        check('reference change rendered',page.locator('#comparisonLabel').inner_text().startswith('着慣れたシャツ'))
        check('reference persisted',json.loads(page.evaluate('localStorage.getItem("sunkan-v1")'))['state']['reference']['width']==56)
        page.locator('#preference').select_option('4')
        check('preference persisted',json.loads(page.evaluate('localStorage.getItem("sunkan-v1")'))['state']['preference']==4)
        page.locator('#tolerance').fill('3')
        page.locator('#tolerance').dispatch_event('change')
        check('tolerance updated',page.locator('#toleranceDisplay').inner_text()=='±3cm')
        page.locator('[data-shrink="5,5"]').click()
        check('shrink preset filled vertical',page.locator('#shrinkV').input_value()=='5')
        check('shrink preset filled horizontal',page.locator('#shrinkH').input_value()=='5')
        page.locator('#itemName').fill('試作テストシャツ')
        page.locator('#itemSize').fill('XXL')
        page.locator('#item-length').fill('72')
        page.locator('#item-width').fill('58')
        page.locator('#item-shoulder').fill('50')
        page.locator('#item-sleeve').fill('60')
        page.locator('#addForm button[type=submit]').click()
        check('candidate added',page.locator('.candidate').count()==5)
        check('new item visible',page.get_by_text('試作テストシャツ').count()>=1)
        check('size input clears',page.locator('#itemSize').input_value()=='')
        saved=page.evaluate('localStorage.getItem("sunkan-v1")')
        load_page(page, {'sunkan-v1':saved})
        check('reload preserves cards',page.locator('.candidate').count()==5)
        check('reload preserves reference',page.locator('#ref-width').input_value()=='56')
        check('reload preserves preference',page.locator('#preference').input_value()=='4')
        # html injection must not execute
        page.locator('#itemName').fill('<img src=x onerror=alert(1)>')
        page.locator('#itemSize').fill('M')
        page.locator('#addForm button[type=submit]').click()
        check('suspicious name preserved as text',page.get_by_text('<img src=x onerror=alert(1)>').count()>=1)
        check('no injected img elements',page.locator('.candidate img').count()==0)
        check('six cards',page.locator('.candidate').count()==6)
        page.locator('.candidate').filter(has_text='試作テストシャツ').locator('[data-remove]').click()
        check('delete candidate',page.locator('.candidate').count()==5)
        check('deleted item not visible',page.get_by_text('試作テストシャツ').count()==0)
        with page.expect_download() as info:
            page.locator('#saveJson').click()
        payload=json.loads(info.value.path().read_text(encoding='utf-8'))
        check('JSON export contains state',payload['version']==1 and len(payload['state']['items'])==5)
        with page.expect_download() as info:
            page.locator('#saveCsv').click()
        content=info.value.path().read_text(encoding='utf-8-sig')
        check('CSV export header',content.startswith('商品名,サイズ,着丈,身幅,肩幅,袖丈'))
        with page.expect_download() as info:
            page.locator('#templateBtn').click()
        check('CSV example export',info.value.suggested_filename=='sunkan-template.csv')
        page.locator('#csvFile').set_input_files({'name':'items.csv','mimeType':'text/csv','buffer':'商品名,サイズ,着丈,身幅,肩幅,袖丈\nCSVの商品,S,68,54,47,59'.encode()})
        page.wait_for_function('document.querySelectorAll(".candidate").length === 6')
        check('CSV imported one',page.locator('.candidate').count()==6)
        page.locator('#csvFile').set_input_files({'name':'bad.csv','mimeType':'text/csv','buffer':'foo,bar\nA,B'.encode()})
        page.wait_for_function('document.querySelector("#message")?.classList.contains("error")')
        check('CSV error visible',page.locator('#message.error').count()==1)
        check('invalid CSV no partial import',page.locator('.candidate').count()==6)
        page.locator('#jsonFile').set_input_files({'name':'test.json','mimeType':'application/json','buffer':json.dumps(payload,ensure_ascii=False).encode()})
        page.wait_for_function('document.querySelectorAll(".candidate").length === 5')
        check('JSON restore number',page.locator('.candidate').count()==5)
        page.locator('#jsonFile').set_input_files({'name':'corrupt.json','mimeType':'application/json','buffer':b'{broken'})
        page.wait_for_function('document.querySelector("#message")?.textContent.includes("復元失敗")')
        check('corrupt JSON error',page.locator('#message.error').count()==1)
        check('corrupt JSON unchanged',page.locator('.candidate').count()==5)
        page.on('dialog',lambda d:d.accept())
        page.locator('#clearBtn').click()
        check('clear removes all',page.locator('.candidate').count()==0)
        check('empty state message',page.locator('.empty').count()==1)
        page.locator('#demoBtn').click()
        check('demo restores four',page.locator('.candidate').count()==4)
        page.locator('#category').select_option('bottom')
        check('bottom reference field',page.locator('#ref-waist').count()==1)
        check('bottom candidate 2',page.locator('.candidate').count()==2)
        check('bottom waist correct',page.locator('#ref-waist').input_value()=='40')
        page.locator('#preference').select_option('6')
        check('bottom preference note', 'わたり幅' in page.locator('#preferenceNote').inner_text())
        page.locator('#category').select_option('top')
        check('top switch demo',page.locator('.candidate').count()==4)
        page.locator('#resetBtn').click()
        check('reset storage deleted',page.evaluate('localStorage.getItem("sunkan-v1")') is None)
        check('no page errors',len(errors)==0)
        page.screenshot(path=str(ROOT/'desktop.png'),full_page=True)
        context2=browser.new_context(viewport={'width':390,'height':844},device_scale_factor=1)
        mobile=context2.new_page()
        load_page(mobile)
        check('mobile displays four cards',mobile.locator('.candidate').count()==4)
        check('mobile no page horizontal overflow',mobile.evaluate('document.documentElement.scrollWidth <= window.innerWidth+1'))
        mobile.screenshot(path=str(ROOT/'mobile.png'),full_page=True)
        context2.close()
        browser.close()
    print(f'PASS {len(checks)}/{len(checks)} browser checks')
    for n,c in enumerate(checks,1):print(f'  {n:02d} {c}')
    return len(checks)

if __name__=='__main__':run()
