"""Functional Chromium smoke tests for FUDA AKARI.
Admin blocks file:// navigation, so the exact three local source files are inlined
in a browser page. LocalStorage persistence in normal file:// origin is not tested.
Run: python browser_test.py
"""
from pathlib import Path
from playwright.sync_api import sync_playwright
import json

ROOT = Path(__file__).resolve().parent
HTML=(ROOT/'index.html').read_text(encoding='utf-8')
HTML=HTML.replace('<link rel="stylesheet" href="style.css">','<style>'+(ROOT/'style.css').read_text()+'</style>')
HTML=HTML.replace('<script src="engine.js"></script>','<script>'+(ROOT/'engine.js').read_text()+'</script>')
HTML=HTML.replace('<script src="app.js"></script>','<script>'+(ROOT/'app.js').read_text()+'</script>')

def run():
    passed=[]
    def check(name, test):
        assert test, f'FAILED: {name}'
        passed.append(name)
    with sync_playwright() as p:
        browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox','--disable-dev-shm-usage'])
        context=browser.new_context(viewport={'width':1440,'height':960},accept_downloads=True,device_scale_factor=1)
        page=context.new_page()
        errors=[]
        page.on('pageerror',lambda e:errors.append(str(e)))
        page.set_content(HTML,wait_until='load')
        check('title', '札あかり' in page.title())
        check('sample work count',page.locator('#workCount').inner_text()=='3')
        check('sample label count',page.locator('#labelCount').inner_text()=='3')
        check('sample preview',page.locator('#paperPreview .card-preview').count()==3)
        check('default language',page.locator('#lang').input_value()=='both')
        check('format label', '95 × 125' in page.locator('#formatDesc').inner_text())
        check('save available',page.locator('#exportJson').is_enabled())
        check('no initial warnings',page.locator('.quality-summary').inner_text().find('基本チェック OK')>=0)
        check('two colors', page.locator('#ink').input_value() != page.locator('#paper').input_value())
        check('responsive preview reduced',float(page.locator('#paperPreview').evaluate('(el) => getComputedStyle(el).zoom'))<1)
        page.screenshot(path=str(ROOT/'desktop.png'),full_page=True)
        page.locator('#format').select_option('compact')
        check('compact grid',page.locator('#format').input_value()=='compact')
        page.locator('#lang').select_option('ja')
        check('Japanese only hides English description',page.locator('.card-preview .body-en').count()==0)
        page.locator('#lang').select_option('both')
        check('bilingual restored',page.locator('.card-preview .body-en').count()>0)
        page.locator('#font').fill('19')
        check('font updated',page.locator('#fontText').inner_text()=='19pt')
        page.locator('#ink').fill('#dddddd')
        check('contrast warning', 'コントラスト' in page.locator('#issueList').inner_text())
        page.locator('#ink').fill('#25334a')
        check('contrast recovered','コントラスト' not in page.locator('#issueList').inner_text())
        page.locator('#workSelect').select_option('0')
        page.locator('#field-title').fill('改訂されたタイトル')
        check('edit previews immediately', '改訂されたタイトル' in page.locator('#paperPreview').inner_text())
        page.locator('#field-noteEn').fill('')
        check('missing English flagged', '英語の題名または解説' in page.locator('#issueList').inner_text())
        page.locator('#field-noteEn').fill('A new test description.')
        check('English warning cleared','英語の題名または解説' not in page.locator('#issueList').inner_text())
        page.locator('#addWork').click()
        check('add work',page.locator('#workCount').inner_text()=='4')
        check('add selects work',page.locator('#field-title').input_value()=='新しい作品')
        page.locator('#deleteWork').click()
        check('delete work',page.locator('#workCount').inner_text()=='3')
        page.locator('#workSelect').select_option('0')
        page.locator('#field-note').fill('長い解説。' * 550)
        check('continuation card',int(page.locator('#labelCount').inner_text())>4)
        check('continuation notice','省略せず' in page.locator('#issueList').inner_text())
        check('has multiple A4 pages',int(page.locator('#pageCount').inner_text())>1)
        old=page.locator('#pageIndicator').inner_text()
        page.locator('#nextPage').click()
        check('next page changes',page.locator('#pageIndicator').inner_text()!=old)
        page.locator('#prevPage').click()
        check('previous page restored',page.locator('#pageIndicator').inner_text()==old)
        with page.expect_download() as di:page.locator('#exportSvg').click()
        svg=di.value.path().read_text(encoding='utf-8')
        check('SVG dimensions', 'width="210mm" height="297mm"' in svg)
        check('SVG contains edited title','改訂されたタイトル' in svg)
        with page.expect_download() as di:page.locator('#exportJson').click()
        project=json.loads(di.value.path().read_text(encoding='utf-8'))
        check('JSON serializes edited title',project['works'][0]['title']=='改訂されたタイトル')
        with page.expect_download() as di:page.locator('#exportCsv').click()
        csv=di.value.path().read_text(encoding='utf-8')
        check('CSV exports edited title','改訂されたタイトル' in csv)
        page.locator('#fileInput').set_input_files(files={'name':'saved.json','mimeType':'application/json','buffer':json.dumps(project).encode('utf-8')})
        check('JSON import restores works',page.locator('#workCount').inner_text()=='3')
        check('JSON import restores field',page.locator('#field-title').input_value()=='改訂されたタイトル')
        sample_csv='code,artist,title,titleEn,year,medium,mediumEn,note,noteEn\n"99","テスト","CSV取込","From CSV","2026","油彩","Oil","日本語","English"\n'
        page.locator('#fileInput').set_input_files(files={'name':'sample.csv','mimeType':'text/csv','buffer':sample_csv.encode('utf-8')})
        check('CSV import replaces artworks',page.locator('#workCount').inner_text()=='1')
        check('CSV imported title',page.locator('#field-title').input_value()=='CSV取込')
        page.locator('#field-title').fill('<script>injection()</script>')
        check('HTML injection displayed as text','injection()' in page.locator('#paperPreview').inner_text())
        check('HTML injection not rendered',page.locator('#paperPreview script').count()==0)
        page.locator('#showCrop').uncheck()
        check('crop marks turn off',page.locator('.trim').count()==0)
        page.evaluate("window.print = () => {window.__printed = true}")
        page.locator('#printBtn').click()
        check('print invokes dialog',page.evaluate('window.__printed===true'))
        check('print DOM generated',page.locator('#printArea .print-page').count()==1)
        check('no JS errors',len(errors)==0)
        # Mobile independent page
        mobile=browser.new_context(viewport={'width':390,'height':844},device_scale_factor=1,accept_downloads=True).new_page()
        mobile.set_content(HTML,wait_until='load')
        check('mobile controls visible',mobile.locator('#workSelect').is_visible())
        check('mobile preview visible',mobile.locator('#paperPreview').is_visible())
        check('mobile fits window', mobile.evaluate('document.documentElement.scrollWidth <= window.innerWidth+2'))
        mobile.screenshot(path=str(ROOT/'mobile.png'),full_page=True)
        browser.close()
    print(f'PASS {len(passed)}/{len(passed)} browser assertions')
    for i,n in enumerate(passed,1):print(f'{i:02d}. {n}')
if __name__=='__main__':run()