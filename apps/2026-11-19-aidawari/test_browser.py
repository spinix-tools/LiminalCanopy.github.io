from pathlib import Path
from playwright.sync_api import sync_playwright
from urllib.parse import urljoin

base=Path(__file__).parent
checks=[]
def ok(name,condition):
    checks.append((name,bool(condition)))
    if not condition: raise AssertionError(name)

with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox','--disable-dev-shm-usage'])
    page=browser.new_page(viewport={'width':1366,'height':960},accept_downloads=True)
    errors=[]
    page.on('pageerror',lambda e: errors.append(str(e)))
    page.evaluate("Object.defineProperty(window, 'localStorage',{configurable:true,value: {getItem(k){return this[k]||null},setItem(k,v){this[k]=v},removeItem(k){delete this[k]}}})")
    page.set_content((base/'index.html').read_text(encoding='utf8'))
    page.wait_for_selector('.expense')
    ok('JS exceptions: zero',len(errors)==0)
    ok('demo 4 members',page.locator('.member').count()==4)
    ok('demo 3 expenses',page.locator('.expense').count()==3)
    ok('demo total correct',page.locator('#grandTotal').inner_text()=='¥61,200')
    result=page.evaluate('AIDAWARI.calculate(AIDAWARI.DEMO)')
    ok('conservation demo shares',sum(x['share'] for x in result['balances'].values())==61200)
    ok('conservation demo net',sum(x['net'] for x in result['balances'].values())==0)
    ok('settlement total valid',sum(x['amount'] for x in result['settlement'])==sum(-v['net'] for v in result['balances'].values() if v['net']<0))
    ok('overlap inclusive',page.evaluate("AIDAWARI.overlap('2026-11-19','2026-11-21','2026-11-20','2026-11-22')")==2)
    ok('no overlap',page.evaluate("AIDAWARI.overlap('2026-11-19','2026-11-21','2026-11-22','2026-11-23')")==0)
    ok('exact remainder allocation',page.evaluate('AIDAWARI.allocate(5,[1,1,1])')==[2,2,1])
    ok('weighted allocation',page.evaluate('AIDAWARI.allocate(900,[2,1])')==[600,300])
    ok('zero weights throw',page.evaluate('(()=>{try{AIDAWARI.allocate(10,[0,0]);return false}catch{return true}})()'))
    ok('clean bad date throws',page.evaluate("(()=>{try{AIDAWARI.clean({members:[{id:'x',name:'X',from:'2026-02-31',to:'2026-03-01',weight:1}],expenses:[],transfers:[]});return false}catch{return true}})()"))
    ok('expense detail',page.locator('.expense summary').count()==3)
    page.locator('.expense summary').first.click()
    ok('expense breakdown opens',page.locator('.expense details').first.get_attribute('open') is not None)
    page.locator('.expense button[data-action="editExpense"]').first.click()
    ok('edit mode',page.locator('#saveExpense').inner_text()=='変更を保存')
    page.locator('#expenseForm input[name="amount"]').fill('37000')
    page.locator('#saveExpense').click()
    ok('edit saved amount',page.locator('#grandTotal').inner_text()=='¥62,200')
    page.locator('.expense button[data-action="deleteExpense"]').last.click()
    ok('deleting expense',page.locator('.expense').count()==2)
    ok('after delete total',page.locator('#grandTotal').inner_text()=='¥45,400')
    page.locator('#memberForm input[name="name"]').fill('新人')
    page.locator('#memberForm input[name="from"]').fill('2026-11-19')
    page.locator('#memberForm input[name="to"]').fill('2026-11-22')
    page.locator('#memberForm button[type="submit"]').click()
    ok('participant add',page.locator('.member').count()==5)
    page.locator('.member').last.locator('input[data-k="weight"]').fill('0.5')
    page.locator('.member').last.locator('input[data-k="weight"]').press('Tab')
    ok('participant edit weight',page.locator('.member').last.locator('input[data-k="weight"]').input_value()=='0.5')
    page.locator('#expenseForm input[name="title"]').fill('共同交通費')
    page.locator('#expenseForm input[name="amount"]').fill('10000')
    page.locator('#expenseForm input[name="from"]').fill('2026-11-19')
    page.locator('#expenseForm input[name="to"]').fill('2026-11-22')
    page.locator('#saveExpense').click()
    ok('add expense',page.locator('.expense').count()==3)
    ok('new total',page.locator('#grandTotal').inner_text()=='¥55,400')
    before=page.locator('#paymentTotal').inner_text()
    if page.locator('button[data-action="record"]').count():
        page.locator('button[data-action="record"]').first.click()
        ok('record transfer',page.locator('#transferList button[data-action="undo"]').count()==1)
        page.locator('#transferList button[data-action="undo"]').first.click()
        ok('undo transfer',page.locator('#transferList button[data-action="undo"]').count()==0)
    else: ok('transfer action available',False)
    with page.expect_download() as dl:
        page.locator('#exportJson').click()
    file=dl.value
    ok('export JSON filename',file.suggested_filename=='aidawari-data.json')
    with page.expect_download() as dl2:
        page.locator('#exportCsv').click()
    ok('export CSV filename',dl2.value.suggested_filename=='aidawari-report.csv')
    ok('auto saved',page.evaluate("!!localStorage.getItem('aidawari-v1')"))
    page.set_content((base/'index.html').read_text(encoding='utf8'))
    ok('reload persistence',page.locator('#grandTotal').inner_text()=='¥55,400')
    page.screenshot(path=str(base/'desktop.png'),full_page=True)
    mobile=browser.new_page(viewport={'width':390,'height':844},device_scale_factor=1)
    mobile.set_content((base/'index.html').read_text(encoding='utf8'))
    mobile.wait_for_selector('.expense')
    ok('mobile no horizontal scroll',mobile.evaluate('document.documentElement.scrollWidth <= window.innerWidth+2'))
    mobile.screenshot(path=str(base/'mobile.png'),full_page=True)
    browser.close()

for n,c in checks: print(('PASS' if c else 'FAIL'),n)
print('TOTAL',len(checks),'PASS',sum(c for _,c in checks))