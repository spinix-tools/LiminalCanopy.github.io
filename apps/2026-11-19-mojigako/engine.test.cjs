const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const html=fs.readFileSync(__dirname+'/index.html','utf8');
const engine=html.match(/<script id="engine">([\s\S]*?)<\/script>/)?.[1];
assert.ok(engine,'engine should be embedded in index.html');
const box={window:{}};vm.runInNewContext(engine,box);
const E=box.window.MojiEngine;
function measure(x,w,f){return E.approximateLines(x,w,f)}
test('JSON: proper input and UTF-8',()=>{assert.equal(E.parseJson('{"日本語":"こんにちは"}')['日本語'],'こんにちは')});
test('JSON: invalid syntax rejected',()=>assert.throws(()=>E.parseJson('{oops')));
test('JSON: top-level array rejected',()=>assert.throws(()=>E.parseJson('[]')));
test('JSON: nested value rejected',()=>assert.throws(()=>E.parseJson('{"a":{"x":1}}')));
test('JSON: numerical value rejected',()=>assert.throws(()=>E.parseJson('{"a":42}')));
test('JSON: key limit',()=>{const o=Object.fromEntries(Array.from({length:301},(_,i)=>['k'+i,'x']));assert.throws(()=>E.validateFlat(o))});
test('tokens are sorted, including escaped braces and printf',()=>assert.equal([...E.tokens('Hi {{ x }} {count} %2$s')].join('|'),'%2$s|{count}|{{x}}'));
test('token mismatch detects a rename',()=>assert.equal(E.tokenMismatch('hi {count}','hi {total}'),true));
test('token mismatch detects lost duplicate',()=>assert.equal(E.tokenMismatch('{x} {x}','{x}'),true));
test('token order can differ',()=>assert.equal(E.tokenMismatch('{a} {b}','{b} {a}'),false));
test('pseudo translation protects tokens',()=>{const r=E.pseudo('hello {count}, {{name}} %s',80);assert.match(r,/\{count\}/);assert.match(r,/\{\{name\}\}/);assert.match(r,/%s/);assert.equal(E.tokenMismatch('hello {count}, {{name}} %s',r),false)});
test('pseudo translation grows',()=>assert.ok(E.pseudo('abcdef',35).length>'abcdef'.length));
test('pseudo translation clamps ratio',()=>assert.ok(E.pseudo('a',999).length<10));
test('CSV injection guarded',()=>assert.equal(E.csvCell('=1+2'),'"\'=1+2"'));
test('CSV quotes escaped',()=>assert.equal(E.csvCell('a"b'),'"a""b"'));
test('audit missing translation',()=>{const r=E.checkFlat({a:'日本語'},{}, {},150,2,15,measure);assert.equal(r[0].critical,true);assert.ok(r[0].problems.includes('訳文なし'))});
test('audit extra target key',()=>{const r=E.checkFlat({a:'x'},{a:'y',z:'extra'}, {},150,2,15,measure);assert.ok(r.find(x=>x.key==='z').problems.includes('余分なキー'))});
test('audit detects overflow',()=>{const r=E.checkFlat({a:'x'},{a:'long lengthy string here'}, {a:{width:50,lines:1}},150,2,15,measure);assert.equal(r[0].overflow,true)});
test('audit does not mark matching tokens',()=>{const r=E.checkFlat({a:'やあ {name}'},{a:'Hello {name}'}, {},300,2,15,measure);assert.equal(r[0].critical,false)});
test('audit marks unchanged as advisory',()=>{const r=E.checkFlat({a:'Saved'},{a:'Saved'}, {},300,2,15,measure);assert.equal(r[0].critical,false);assert.ok(r[0].problems.includes('原文のまま'))});
test('estimated lines respect newline',()=>assert.equal(E.approximateLines('abc\ndef',500,14),2));
test('estimated lines respect Japanese width',()=>assert.ok(E.approximateLines('日本語日本語',20,16)>=3));
test('no HTML dependencies / external requests',()=>{assert.doesNotMatch(html,/<script[^>]+src=/i);assert.doesNotMatch(html,/<link[^>]+href="https?:/i)});
