"""Playwright offline HTML smoke and functional assertions. Run: python browser_test.py"""
import asyncio,json,pathlib,re
from playwright.async_api import async_playwright
ROOT=pathlib.Path(__file__).parent
def bundled_html():
    html=(ROOT/'index.html').read_text()
    css=(ROOT/'style.css').read_text()
    engine=(ROOT/'engine.js').read_text()
    app=(ROOT/'app.js').read_text()
    html=html.replace('<link rel="stylesheet" href="style.css">','<style>'+css+'</style>')
    html=html.replace('<script src="engine.js"></script>','<script>'+engine+'</script>')
    html=html.replace('<script src="app.js"></script>','<script>'+app+'</script>')
    return html
async def open_inline(page):
    await page.evaluate("""() => {let box = {}; Object.defineProperty(window,'localStorage',{configurable:true,value:{getItem:k=>box[k]||null,setItem:(k,v)=>box[k]=String(v),removeItem:k=>delete box[k]}})}""")
    await page.set_content(bundled_html(),wait_until='load')
async def main():
    checks=0
    def ok(cond,reason):
        nonlocal checks
        assert cond,reason
        checks+=1
    async with async_playwright() as pw:
        browser=await pw.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox','--allow-file-access-from-files'])
        context=await browser.new_context(viewport={'width':1440,'height':1000},accept_downloads=True)
        page=await context.new_page()
        errors=[]
        page.on('pageerror',lambda e:errors.append(str(e)))
        # Chromium admin policy blocks file://; inject identical HTML/CSS/JS and mock storage.
        await open_inline(page)
        await page.locator('#p90').wait_for(state='visible')
        ok(await page.title()=='列予報 | イベントの行列を、前日に減らす。','title')
        ok(await page.locator('.slots tbody tr').count()==6,'six time slots')
        ok('分' in (await page.locator('#p90').inner_text()),'forecast shown')
        ok('分' in (await page.locator('#average').inner_text()),'mean displayed')
        ok('人' in (await page.locator('#peak').inner_text()),'queue displayed')
        ok('%' in (await page.locator('#over').inner_text()),'fraction displayed')
        ok(await page.locator('#chart svg').count()==1,'chart svg')
        ok(await page.locator('#adviceBody strong').count()>=1,'recommended slot')
        ok(await page.locator('#applyAdvice').is_enabled(),'apply enabled')
        ok(not errors,f'js errors: {errors}')
        await page.screenshot(path=str(ROOT/'desktop.png'),full_page=True)
        original=await page.locator('#p90').inner_text()
        await page.locator('#slotsBody input[data-i="2"][data-j="2"]').fill('5')
        await page.wait_for_timeout(350)
        ok((await page.locator('#p90').inner_text()) != original,'staff change updates simulation')
        await page.locator('#addSlot').click()
        ok(await page.locator('.slots tbody tr').count()==7,'slot add')
        await page.locator('#removeSlot').click()
        ok(await page.locator('.slots tbody tr').count()==6,'slot remove')
        await page.locator('#start').fill('23:30')
        await page.locator('#start').dispatch_event('change')
        ok('00:00' in (await page.locator('#slotsBody').inner_text()),'midnight wrap')
        await page.locator('#sampleMarket').click()
        ok((await page.locator('#eventName').input_value())=='マルシェ販売','market preset')
        ok((await page.locator('#service').input_value())=='2.3','market service')
        await page.locator('#sampleReception').click()
        ok((await page.locator('#eventName').input_value())=='地域イベント受付','reception preset')
        await page.locator('#sampleFestival').click()
        ok((await page.locator('#eventName').input_value())=='学園祭・模擬店','festival preset')
        await page.locator('#limit').fill('0')
        await page.wait_for_timeout(350)
        ok(await page.locator('#error').is_visible(),'invalid limit error')
        await page.locator('#limit').fill('8')
        await page.wait_for_timeout(350)
        ok(not await page.locator('#error').is_visible(),'error recovers')
        before=await page.locator('#slotsBody input[data-i="2"][data-j="2"]').input_value()
        await page.locator('#applyAdvice').click()
        ok(await page.locator('#slotsBody input[data-i="2"][data-j="2"]').input_value()!=before,'apply modifies staff')
        # file download JSON; restore settings
        await page.locator('#eventName').fill('レコード検証')
        await page.wait_for_timeout(250)
        async with page.expect_download() as d:
            await page.locator('#jsonBtn').click()
        download=await d.value
        ok(download.suggested_filename=='retsuyoho-plan.json','json export filename')
        file=ROOT/'test-export.json';await download.save_as(str(file))
        v=json.loads(file.read_text())
        ok(v['plan']['name']=='レコード検証','json export content')
        await page.locator('#eventName').fill('一時的な変更')
        await page.locator('#importFile').set_input_files(str(file))
        await page.wait_for_timeout(150)
        ok(await page.locator('#eventName').input_value()=='レコード検証','json import restores')
        async with page.expect_download() as d:
            await page.locator('#csvBtn').click()
        csv=(ROOT/'test-forecast.csv');await (await d.value).save_as(str(csv))
        ok('時間帯' in csv.read_text(encoding='utf-8-sig'),'csv headers')
        ok('10:00-10:30' in csv.read_text(encoding='utf-8-sig'),'csv intervals')
        await page.set_content(bundled_html(),wait_until="load")
        ok(await page.locator('#eventName').input_value()=='レコード検証','localStorage persistence')
        await page.locator('#resetBtn').click()
        ok(await page.locator('#eventName').input_value()=='学園祭・模擬店','reset')
        await page.locator('#seed').fill('41')
        await page.wait_for_timeout(300)
        ok(await page.locator('#runLabel').is_visible(),'seed redraw')
        await page.locator('#trials').select_option('40')
        await page.wait_for_timeout(350)
        ok('40回' in await page.locator('#runLabel').inner_text(),'trial setting')
        ok(not errors,f'js errors after interaction: {errors}')
        await context.close()
        mobile=await browser.new_context(viewport={'width':390,'height':844},is_mobile=True,device_scale_factor=1)
        mp=await mobile.new_page();await open_inline(mp)
        await mp.screenshot(path=str(ROOT/'mobile.png'),full_page=True)
        ok(await mp.locator('#p90').is_visible(),'mobile metrics')
        ok(await mp.locator('#chart svg').count()==1,'mobile chart')
        ok((await mp.locator('body').evaluate('(el)=>el.scrollWidth'))<=400,'mobile overflow')
        await browser.close()
    print(f'CHROMIUM_ASSERTIONS={checks} all passed')
if __name__=='__main__':asyncio.run(main())
