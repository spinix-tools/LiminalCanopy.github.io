"""Playwright + Chromium functional checks. Run: python browser_test.py.
In managed environments file:// can be blocked; source is loaded inline and localStorage simulated.
"""
import json, pathlib
from playwright.sync_api import sync_playwright

HERE = pathlib.Path(__file__).resolve().parent
checks=[]
def ok(cond,desc):
    checks.append((desc,bool(cond)))
    if not cond: raise AssertionError(desc)

with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox'])
    context=browser.new_context(accept_downloads=True,viewport={'width':1366,'height':940})
    page=context.new_page()
    errors=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    source=(HERE/'index.html').read_text()
    source=source.replace('<link rel="stylesheet" href="style.css">','<style>'+ (HERE/'style.css').read_text()+'</style>')
    source=source.replace('<script src="engine.js"></script>','<script>'+(HERE/'engine.js').read_text()+'</script>')
    source=source.replace('<script src="app.js"></script>','<script>'+(HERE/'app.js').read_text()+'</script>')
    page.goto('about:blank')
    page.evaluate("window.__store={};Object.defineProperty(window,'localStorage',{value:{getItem:k=>window.__store[k]||null,setItem:(k,v)=>window.__store[k]=v}})")
    page.set_content(source)
    page.wait_for_selector('#months .barcol')
    ok(page.title().startswith('ひなた窓'),'タイトル表示')
    ok(page.locator('#months .barcol').count()==12,'12か月グラフ')
    ok(page.locator('#timelineNear .slot').count()==144,'10分スロット144個')
    ok(page.locator('#timelineFar .slot').count()==144,'比較側144個')
    ok(page.locator('#nearHours').inner_text().endswith('h'),'日照時間数値')
    ok(page.locator('#reasons .reason').count()>=1,'日陰の原因')
    page.locator('[data-season="06-21"]').click()
    ok(page.locator('[name="date"]').input_value()=='2026-06-21','夏至変更')
    summer=page.locator('#nearHours').inner_text()
    page.locator('[data-season="12-21"]').click()
    ok(page.locator('[name="date"]').input_value()=='2026-12-21','冬至変更')
    winter=page.locator('#nearHours').inner_text()
    ok(summer!=winter,'季節で異なる計算')
    page.locator('[data-city="sapporo"]').click()
    ok(page.locator('[name="lat"]').input_value()=='43.06','札幌プリセット')
    page.locator('[data-city="tokyo"]').click()
    ok(page.locator('[name="lat"]').input_value()=='35.68','東京プリセット')
    page.locator('[name="face"]').select_option('0')
    ok(page.locator('#nearHours').inner_text()=='0.0h','北向き冬季は直射ゼロ')
    page.locator('[name="face"]').select_option('180')
    page.locator('[name="overhang"]').fill('0')
    ok(page.locator('#nearHours').inner_text()!='0.0h','庇設定を変更すると計算更新')
    page.locator('#saveBtn').click()
    ok('保存しました' in page.locator('#notice').inner_text(),'端末保存の確認')
    page.set_content(source);page.wait_for_selector('#months .barcol')
    ok(page.locator('[name="overhang"]').input_value()=='0','再読込時の保存復元')
    with page.expect_download() as dl: page.locator('#exportBtn').click()
    data=json.loads(pathlib.Path(dl.value.path()).read_text())
    ok(data['app']=='hinatamado' and data['settings']['overhang']==0,'JSON出力内容')
    with page.expect_download() as dl: page.locator('#csvBtn').click()
    csv=pathlib.Path(dl.value.path()).read_bytes()
    ok(csv.startswith(b'\xef\xbb\xbf'),'CSV UTF-8 BOM')
    ok(len(csv.decode('utf-8-sig').splitlines())==145,'CSV 144行')
    page.locator('#resetBtn').click()
    ok(page.locator('[name="overhang"]').input_value()=='65','サンプル復元')
    page.locator('#importFile').set_input_files({'name':'backup.json','mimeType':'application/json','buffer':json.dumps(data,ensure_ascii=False).encode()})
    ok(page.locator('[name="overhang"]').input_value()=='0','JSON再読込')
    ok('読み込みました' in page.locator('#notice').inner_text(),'復元結果')
    page.locator('[name="lat"]').fill('999')
    ok('許容範囲' in page.locator('#notice').inner_text(),'不正値警告')
    page.locator('[name="lat"]').fill('35.68')
    ok(not errors,'ブラウザ例外ゼロ: '+str(errors))
    page.screenshot(path=str(HERE/'desktop.png'),full_page=True)
    page.set_viewport_size({'width':390,'height':844})
    page.screenshot(path=str(HERE/'mobile.png'),full_page=True)
    ok(page.locator('#nearHours').is_visible(),'モバイル表示')
    ok(page.evaluate('document.documentElement.scrollWidth <= window.innerWidth+1'),'モバイル横スクロールなし')
    browser.close()

for desc,_ in checks: print('PASS',desc)
print(f'{len(checks)}/{len(checks)} browser assertions PASS')
