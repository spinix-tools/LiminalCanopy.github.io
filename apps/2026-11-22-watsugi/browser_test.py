"""Offline functional browser smoke tests. pip playwright & local Chromium required."""
import asyncio, json
from pathlib import Path
from playwright.async_api import async_playwright
ROOT=Path(__file__).parent
checks=[]
def page_html():
    html=(ROOT/'index.html').read_text()
    return (html.replace('<link rel="stylesheet" href="style.css">','<style>'+ (ROOT/'style.css').read_text() + '</style>')
       .replace('<script src="engine.js"></script>','<script>'+(ROOT/'engine.js').read_text()+'</script>')
       .replace('<script src="app.js"></script>','<script>'+(ROOT/'app.js').read_text()+'</script>'))
def check(label, condition):
    if not condition: raise AssertionError(label)
    checks.append(label)

async def main():
  async with async_playwright() as pw:
    browser=await pw.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
    context=await browser.new_context(viewport={'width':1440,'height':1000},accept_downloads=True,locale='ja-JP')
    page=await context.new_page();errors=[];requests=[]
    page.on('pageerror',lambda error:errors.append(str(error)))
    page.on('console',lambda message: errors.append(message.text) if message.type=='error' else None)
    page.on('request',lambda request: requests.append(request.url) if request.url.startswith(('http:','https:')) else None)
    await page.set_content(page_html(),wait_until='load')
    await page.wait_for_selector('.table-card')
    check('page title', '輪つぎ' in await page.title())
    check('no external requests', not requests)
    check('initial 14 people',len(await page.locator('#attendance tbody tr').all())==14)
    check('4 tabs',await page.locator('#tabs button').count()==4)
    check('3 table cards',await page.locator('.table-card').count()==3)
    check('0 committed initially','0 / 4' in await page.locator('#lockedPill').inner_text())
    check('numeric unique count', (await page.locator('#unique').inner_text()).isdigit())
    check('initial positive waiting', '回' in await page.locator('#maxWaiting').inner_text())
    check('attendee table populated',await page.locator('#itinerary tbody tr').count()==14)
    initial_board=await page.locator('#board').inner_text()
    await page.screenshot(path=str(ROOT/'desktop.png'),full_page=True)
    await page.get_by_role('button',name='表示回を確定').click()
    check('first round locked', '1 / 4' in await page.locator('#lockedPill').inner_text())
    check('selected second round',await page.locator('#tabs [aria-selected=true]').inner_text()=='第 2 回')
    check('locked checkboxes disabled',await page.locator('#attendance [data-round="0"]').first.is_disabled())
    check('next round checkbox enabled',await page.locator('#attendance [data-round="1"]').first.is_enabled())
    await page.locator('#attendance [data-round="1"][data-person="0"]').uncheck()
    check('dirty state notice','出欠' in await page.locator('#status').inner_text())
    check('confirm disabled until replanning',await page.locator('#lock').is_disabled())
    check('stale metrics hidden', '—' in await page.locator('#unique').inner_text())
    await page.get_by_role('button',name='変更を反映して再編成').click()
    check('fresh metrics after recompute', (await page.locator('#unique').inner_text()).isdigit())
    check('locked count unchanged','1 / 4' in await page.locator('#lockedPill').inner_text())
    await page.locator('#tabs [data-tab="0"]').click()
    check('committed first round unchanged',initial_board==await page.locator('#board').inner_text())
    await page.locator('#tabs [data-tab="1"]').click()
    check('removed participant absent in 2nd round','P01' in await page.locator('.bottomline').inner_text())
    await page.locator('#lock').click()
    check('two rounds committed','2 / 4' in await page.locator('#lockedPill').inner_text())
    await page.locator('#undo').click()
    check('undo lock','1 / 4' in await page.locator('#lockedPill').inner_text())
    async with page.expect_download() as down:
        await page.locator('#csv').click()
    csv=await down.value
    check('CSV filename', csv.suggested_filename.endswith('.csv'))
    saved=ROOT/'browser-export.csv';await csv.save_as(str(saved))
    content=saved.read_text(encoding='utf-8-sig')
    check('CSV contains waiting and absent','待機' in content and '不参加' in content)
    check('CSV header', '参加者コード' in content)
    async with page.expect_download() as down:
        await page.locator('#json').click()
    exported=ROOT/'browser-export.json';await (await down.value).save_as(str(exported))
    data=json.loads(exported.read_text())
    check('JSON participants count',len(data['participants'])==14)
    check('JSON preserved completed round',data['locked']==1)
    await page.locator('#file').set_input_files(str(exported))
    check('JSON import status','読み込み' in await page.locator('#status').inner_text())
    check('JSON import attendee count',await page.locator('#itinerary tbody tr').count()==14)
    await page.locator('#participants').fill('A01\nB02\nC03\nD04')
    await page.locator('#tables').fill('2')
    await page.locator('#seats').fill('2')
    await page.locator('#rounds').fill('3')
    await page.locator('#apply').click()
    check('new count',await page.locator('#attendance tbody tr').count()==4)
    check('new rounds',await page.locator('#tabs button').count()==3)
    check('new tables',await page.locator('.table-card').count()==2)
    check('new plan unlocked', '0 / 3' in await page.locator('#lockedPill').inner_text())
    await page.locator('#participants').fill('<img src=x onerror=alert(1)>\nB02')
    await page.locator('#apply').click()
    check('XSS text escaped',await page.locator('.personchip img').count()==0)
    check('XSS string visible', '<img' in await page.locator('#itinerary').inner_text())
    await page.locator('#reset').click()
    check('reset demo',await page.locator('#attendance tbody tr').count()==14)
    check('no JS exceptions desktop',not errors)
    mobile=await browser.new_context(viewport={'width':390,'height':844},device_scale_factor=1,accept_downloads=True,is_mobile=True,has_touch=True)
    mpage=await mobile.new_page()
    mobile_errors=[];mpage.on('pageerror',lambda e:mobile_errors.append(str(e)))
    await mpage.set_content(page_html(),wait_until='load')
    await mpage.screenshot(path=str(ROOT/'mobile.png'),full_page=True)
    check('mobile cards rendered',await mpage.locator('.table-card').count()==3)
    check('mobile results present',await mpage.locator('#unique').inner_text()!='—')
    check('mobile tab selectable',await mpage.locator('#tabs button').count()==4)
    check('mobile document no overflow',await mpage.evaluate('document.documentElement.scrollWidth <= window.innerWidth+2'))
    check('no mobile JS errors',not mobile_errors)
    await mobile.close();await context.close();await browser.close()
    print('PASS',len(checks),'/',len(checks))
    for i,c in enumerate(checks,1): print(f'{i:02d}. {c}')

if __name__=='__main__':asyncio.run(main())
