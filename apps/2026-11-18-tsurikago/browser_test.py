"""Chromium E2E smoke test. Run: python browser_test.py"""
from pathlib import Path
import json, re
from playwright.sync_api import sync_playwright
ROOT=Path(__file__).parent
HTML=(ROOT/'index.html').read_text(encoding='utf-8')
HTML=re.sub(r'<link rel="stylesheet" href="style.css">','',HTML)
HTML=re.sub(r'<script src="(?:engine|app).js"></script>','',HTML)
def boot(page,saved=None):
    page.set_content(HTML,wait_until='load')
    page.add_style_tag(content=(ROOT/'style.css').read_text(encoding='utf-8'))
    page.evaluate('''(saved)=>{const mem={};if(saved)mem["tsurikago-config-v1"]=saved;Object.defineProperty(window,"localStorage",{configurable:true,value:{getItem:k=>mem[k]??null,setItem:(k,v)=>{mem[k]=String(v)},removeItem:k=>{delete mem[k]}}});}''',saved)
    page.add_script_tag(content=(ROOT/'engine.js').read_text(encoding='utf-8'))
    page.add_script_tag(content=(ROOT/'app.js').read_text(encoding='utf-8'))
checks=[]
def check(name, cond):
    checks.append((name,bool(cond)))
    if not cond: raise AssertionError(name)
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox','--disable-dev-shm-usage'])
    context=browser.new_context(viewport={'width':1440,'height':920},accept_downloads=True)
    page=context.new_page(); errors=[]
    page.on('pageerror',lambda error: errors.append(str(error)))
    boot(page); page.wait_for_timeout(200)
    check('title', 'つりかご' in page.title())
    check('sample item count',page.locator('#items-body tr').count()==3)
    check('float count',page.locator('.float-input').count()==9)
    check('default result calculated',page.locator('#success-rate').inner_text().endswith('%'))
    check('no console page errors',len(errors)==0)
    check('original total',page.locator('#float-total').inner_text()=='¥18,260')
    page.screenshot(path=str(ROOT/'desktop.png'),full_page=True)
    check('screenshot saved',(ROOT/'desktop.png').stat().st_size>10000)
    baseline=page.locator('#success-rate').inner_text()
    page.locator('#run').click();check('deterministic rerun',page.locator('#success-rate').inner_text()==baseline)
    page.locator('#add-item').click();check('add item',page.locator('#items-body tr').count()==4)
    page.locator('#items-body tr').last.locator('[data-field="name"]').fill('手作りシール');check('edit item',page.locator('#items-body tr').last.locator('[data-field="name"]').input_value()=='手作りシール')
    page.locator('#items-body tr').last.locator('.remove').click();check('remove item',page.locator('#items-body tr').count()==3)
    page.locator('#denom-500').fill('16');check('update float amount',page.locator('#float-total').inner_text()=='¥19,260')
    check('dirty report badge',page.locator('#result-status').inner_text()=='再計算が必要')
    page.locator('#run').click();check('run after edits',page.locator('#result-status').inner_text()!='再計算が必要')
    page.locator('#budget').fill('3000');page.locator('#recommend').click();check('recommend response visible',len(page.locator('#recommend-result').inner_text())>20)
    with page.expect_download() as info: page.locator('#export-csv').click()
    dl=info.value;check('CSV download filename',dl.suggested_filename=='tsurikago-checklist.csv')
    csv_path=ROOT/'download-test.csv';dl.save_as(csv_path);check('CSV content', '500,16,8000' in csv_path.read_text(encoding='utf-8-sig'))
    with page.expect_download() as info:page.locator('#export-json').click()
    dl=info.value;check('JSON download filename',dl.suggested_filename=='tsurikago-settings.json')
    json_path=ROOT/'download-test.json';dl.save_as(json_path);data=json.loads(json_path.read_text());check('export contains edited float',data['float'][3]==16)
    page.locator('#reset').click();check('reset float',page.locator('#denom-500').input_value()=='14')
    page.locator('#import-json').set_input_files(str(json_path));page.wait_for_timeout(150);check('JSON import restore',page.locator('#denom-500').input_value()=='16')
    saved=page.evaluate('localStorage.getItem("tsurikago-config-v1")'); fresh=context.new_page();boot(fresh,saved);check('mock persistence after reinitialization',fresh.locator('#denom-500').input_value()=='16');fresh.close()
    page.locator('#items-body tr').first.locator('[data-field="price"]').fill('0');page.locator('#run').click();check('invalid values rejected or excluded',('入力エラー' in page.locator('#message').inner_text()) or page.locator('#success-rate').inner_text().endswith('%'))
    check('still no page errors',len(errors)==0)
    mobile=browser.new_context(viewport={'width':390,'height':844},device_scale_factor=1,accept_downloads=True)
    mp=mobile.new_page();boot(mp);mp.wait_for_timeout(100)
    check('mobile result visible',mp.locator('#success-rate').inner_text().endswith('%'))
    check('mobile no horizontal scroll',mp.evaluate('document.documentElement.scrollWidth <= innerWidth + 2'))
    mp.screenshot(path=str(ROOT/'mobile.png'),full_page=True)
    check('mobile screenshot saved',(ROOT/'mobile.png').stat().st_size>10000)
    browser.close()
for k,ok in checks:print('PASS' if ok else 'FAIL',k)
print('RESULT',sum(ok for _,ok in checks),'/',len(checks))
