"""Chromium browser checks. Uses exact HTML/CSS/JS inlined because sandbox blocks file:// and localhost."""
from pathlib import Path
import json, re
from playwright.sync_api import sync_playwright
HERE=Path(__file__).parent
html=(HERE/'index.html').read_text()
css=(HERE/'style.css').read_text()
engine=(HERE/'engine.js').read_text()
app=(HERE/'app.js').read_text()
html=html.replace('<link rel="stylesheet" href="style.css">','<style>'+css+'</style>')
html=html.replace('<script src="engine.js"></script>','<script>'+engine+'</script>').replace('<script src="app.js"></script>','<script>'+app+'</script>')
checks=[]
def ok(condition,label):
    checks.append((bool(condition),label))
    if not condition: raise AssertionError(label)
with sync_playwright() as play:
    browser=play.chromium.launch(executable_path='/usr/bin/chromium',args=['--no-sandbox'],headless=True)
    ctx=browser.new_context(viewport={'width':1440,'height':900},accept_downloads=True)
    page=ctx.new_page();errors=[];page.on('pageerror',lambda err: errors.append(str(err)))
    page.set_content(html,wait_until='load')
    ok(page.locator('h1').count()==1,'headline visible')
    ok(page.locator('#slots .slot').count()==6,'six time slots')
    ok(page.locator('#peak').inner_text()!='—','initial peak renders')
    ok('m³' in page.locator('#volume-label').inner_text(),'volume renders')
    ok(page.locator('#chart polyline').count()==2,'both scenario curves render')
    ok(page.locator('#chart line').count()>10,'grid and target line render')
    ok(page.locator('#suggest-body').inner_text()!='計算中…','recommendation renders')
    ok(page.locator('#error').is_hidden(),'no startup error')
    ok(not errors,'no runtime JS errors at startup')
    peak_old=page.locator('#peak').inner_text()
    page.locator('#slots .slot').first.locator('input[type=number]').fill('99')
    ok(page.locator('#peak').inner_text()!=peak_old,'people change recomputes')
    page.locator('#slots .slot').first.locator('input[type=number]').fill('8')
    page.locator('#boostFlow').fill('1000')
    ok(page.locator('#peak').inner_text()!='—','ventilation changes recompute')
    page.locator('#apply-suggest').click()
    ok(page.locator('#slots input[type=checkbox]:checked').count()==2,'suggestion applied to exactly one extra slot')
    page.locator('#add-slot').click()
    ok(page.locator('#slots .slot').count()==7,'new slot added')
    page.locator('#slots .slot').last.locator('.remove').click()
    ok(page.locator('#slots .slot').count()==6,'slot removed')
    page.locator('#start').fill('20:00')
    ok('20:00' in page.locator('#slots .slot').first.locator('.time').inner_text(),'start time adjusts slot labels')
    page.locator('#slotMin').select_option('60')
    ok('21:00' in page.locator('#slots .slot').first.locator('.time').inner_text(),'duration adjusts slot labels')
    page.locator('[data-preset=school]').click()
    ok(page.locator('#name').input_value()=='教室','classroom preset applies')
    ok(page.locator('#threshold').input_value()=='1500','preset threshold applies')
    ok(page.locator('#slots .slot').count()==6,'preset resets schedule')
    page.locator('[data-preset=studio]').click()
    ok(page.locator('#name').input_value()=='創作教室','studio preset applies')
    page.locator('#baseFlow').fill('500')
    ok(not page.locator('#error').is_hidden(),'impossible ventilation input rejected')
    ok(page.locator('#apply-suggest').is_disabled(),'suggestion disabled on invalid input')
    page.locator('#boostFlow').fill('600')
    ok(page.locator('#error').is_hidden(),'errors clear after correction')
    with page.expect_download() as dl:page.locator('#download-csv').click()
    obj=dl.value
    ok(obj.suggested_filename=='ikisuu-results.csv','CSV filename correct')
    ok(obj.path().read_bytes().startswith(b'\xef\xbb\xbf'),'CSV has UTF8 BOM')
    with page.expect_download() as dl:page.locator('#save-json').click()
    obj=dl.value
    ok(obj.suggested_filename=='ikisuu-settings.json','JSON filename correct')
    config=json.loads(obj.path().read_text())
    ok(config['name']=='創作教室' and config['baseFlow']==500,'JSON contains live parameters')
    config['name']='JSON復元のテスト';config['slots'][0]['people']=22
    page.locator('#json-file').set_input_files({'name':'saved.json','mimeType':'application/json','buffer':json.dumps(config).encode()})
    page.wait_for_function("document.querySelector('#name').value==='JSON復元のテスト'")
    ok(page.locator('#name').input_value()=='JSON復元のテスト','import restores label')
    ok(page.locator('#slots .slot').first.locator('input[type=number]').input_value()=='22','import restores occupancy')
    page.locator('#json-file').set_input_files({'name':'bad.json','mimeType':'application/json','buffer':b'{not JSON'})
    page.wait_for_function("document.querySelector('#error').textContent.includes('読み込めませんでした')")
    ok('読み込めませんでした' in page.locator('#error').inner_text(),'bad JSON shows error')
    page.locator('#length').fill('0')
    ok('長さ' in page.locator('#error').inner_text(),'invalid geometry warns')
    page.locator('#length').fill('6')
    ok(page.locator('#error').is_hidden(),'geometry repair clears error')
    page.locator('[data-preset=meeting]').click()
    page.screenshot(path=str(HERE/'desktop.png'),full_page=True)
    mobile_ctx=browser.new_context(viewport={'width':390,'height':844});mobile=mobile_ctx.new_page();mobile.set_content(html,wait_until='load')
    ok(mobile.locator('#peak').inner_text()!='—','mobile results render')
    ok(mobile.evaluate('document.documentElement.scrollWidth <= window.innerWidth + 2'),'mobile no horizontal overflow')
    mobile.screenshot(path=str(HERE/'mobile.png'),full_page=True)
    ok(not errors,'no page JS errors after interactions')
    browser.close()
print(f'Chromium UI: {sum(x[0] for x in checks)}/{len(checks)} passed')
for _,name in checks:print('OK',name)
