'use strict';
const {test}=require('node:test'),assert=require('node:assert/strict'),E=require('./engine.js');
const one=(patch={})=>({name:'sample',countIn:false,segments:[{name:'phase',start:60,end:60,bars:2,beats:4,sub:1,mode:'play',...patch}]});
const eq=(name,actual,expected)=>test(name,()=>assert.deepEqual(actual,expected));
eq('three preset keys',Object.keys(E.PRESETS).length,3);
eq('preset climb has four blocks',E.preset('climb').segments.length,4);
eq('preset trio has 3 subdivision',E.preset('trio').segments[1].sub,3);
eq('preset copy is isolated',(()=>{const p=E.preset('climb');p.segments[0].name='changed';return E.preset('climb').segments[0].name})(),'ゆっくり確認');
eq('single bar exact bpm',E.barBpm({start:70,end:90,bars:1},0),70);
eq('ramp starts at start BPM',E.barBpm({start:70,end:90,bars:3},0),70);
eq('ramp ends at end BPM',E.barBpm({start:70,end:90,bars:3},2),90);
eq('ramp middle interpolates',E.barBpm({start:70,end:90,bars:3},1),80);
eq('down ramp supported',E.barBpm({start:90,end:70,bars:3},1),80);
eq('single bar duration 4sec',E.buildTimeline(one({bars:1})).totalSeconds,4);
eq('two bar duration 8sec',E.buildTimeline(one()).totalSeconds,8);
eq('practice event count',E.buildTimeline(one()).events.length,8);
eq('bar count',E.buildTimeline(one()).bars.length,2);
eq('event 0 accent',E.buildTimeline(one()).events[0].accent,true);
eq('event 1 unaccented',E.buildTimeline(one()).events[1].accent,false);
eq('second bar accent',E.buildTimeline(one()).events[4].accent,true);
eq('subdivision doubles events',E.buildTimeline(one({sub:2})).events.length,16);
eq('triplet event timing',E.buildTimeline(one({bars:1,sub:3})).events[1].t,1/3);
eq('count-in number of beats',E.buildTimeline({...one({bars:1}),countIn:true}).events.filter(x=>x.kind==='count').length,4);
eq('count-in length',E.buildTimeline({...one({bars:1}),countIn:true}).countInSeconds,4);
eq('rest is muted',E.buildTimeline(one({mode:'rest'})).events.every(e=>e.muted),true);
eq('rest takes time',E.buildTimeline(one({mode:'rest'})).totalSeconds,8);
eq('count phase',E.progressAt(E.buildTimeline({...one(),countIn:true}),2).phase,'count');
eq('first practice bar',E.progressAt(E.buildTimeline(one()),0.5).bar,1);
eq('second practice bar',E.progressAt(E.buildTimeline(one()),4.5).bar,2);
eq('done at end',E.progressAt(E.buildTimeline(one()),8).phase,'done');
eq('negative progress clamped',E.progressAt(E.buildTimeline(one()),-20).progress,0);
eq('duration rounds up',E.formatDuration(60.2),'1:01');
eq('duration zero',E.formatDuration(0),'0:00');
eq('tap tempo 120',E.tempoFromTaps([0,500,1000,1500]),120);
eq('tap ignores too short',E.tempoFromTaps([0,100,600]),120);
eq('tap insufficient',E.tempoFromTaps([0]),null);
eq('CSV BOM',E.csv(E.buildTimeline(one())).charCodeAt(0),0xfeff);
eq('CSV has header and 2 bars',E.csv(E.buildTimeline(one())).trim().split('\r\n').length,3);
