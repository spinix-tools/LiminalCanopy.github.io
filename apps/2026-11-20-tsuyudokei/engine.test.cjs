'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const E=require('./engine.js');
const near=(a,b,eps=1e-6)=>assert.ok(Math.abs(a-b)<eps,`${a} not near ${b}`);
const base=()=>E.stateFor('cold');
test('12 two-hour slots with exact time endpoints',()=>{assert.equal(E.TIMES.length,12);assert.equal(E.TIMES[0],'00:00');assert.equal(E.TIMES[11],'22:00')});
test('saturation at 0 C is 6.112 hPa',()=>near(E.saturation(0),6.112));
test('saturation pressure rises with temperature',()=>{for(let t=-29;t<40;t++)assert.ok(E.saturation(t+1)>E.saturation(t))});
test('dew point at 100% equals air temperature',()=>{for(let t=-30;t<=40;t+=5)near(E.dewPoint(t,100),t)});
test('reference dew point 20C 50% is approximately 9.26C',()=>near(E.dewPoint(20,50),9.255,0.05));
test('less relative humidity has a lower dew point',()=>assert.ok(E.dewPoint(20,40)<E.dewPoint(20,70)));
test('base film formula reduces to U * 0.13',()=>near(E.surfaceTemp(20,-5,2.7,.13),20-2.7*.13*25));
test('increasing Rsi drops cold-window surface temperature',()=>assert.ok(E.surfaceTemp(20,-5,5.8,.2)<E.surfaceTemp(20,-5,5.8,.13)));
test('equal indoor/outdoor temperatures keep surface identical',()=>near(E.surfaceTemp(20,20,5.8,.2),20));
test('worse U lowers warm-inside surface temperature',()=>assert.ok(E.surfaceTemp(20,-5,5.8,.13)<E.surfaceTemp(20,-5,1.1,.13)));
test('condensation exactly at dewpoint',()=>{const z=E.evaluateSlot({inside:20,outside:10,rh:50},{u:5.8,rsi:.13,delta:0});near(z.surfaceRH,50*E.saturation(20)/E.saturation(z.ts));assert.equal(z.condense,z.ts<=z.dew+1e-9)});
test('80% ceiling produces exactly 80% surface relative humidity',()=>{const ti=20,ts=8,cap=E.limitRH(ti,ts,80);near(cap*E.saturation(ti)/E.saturation(ts),80)});
test('wetter days give no fewer 80% risk hours',()=>{const a=base(),b=base();b.rows.forEach(r=>r.rh+=10);assert.ok(E.analyze(b).A.dampHours>=E.analyze(a).A.dampHours)});
test('better U gives no more damp hours in cold weather',()=>{const a=base();a.B.delta=a.A.delta;a.B.u=1.1;assert.ok(E.analyze(a).B.dampHours<=E.analyze(a).A.dampHours)});
test('same parameters give exactly same results',()=>{const s=base();s.B={...s.A};const r=E.analyze(s);assert.deepEqual(r.A,r.B);assert.equal(r.savedDampHours,0)});
test('dry/very cold day can condense',()=>{const s=base();const r=E.analyze(s);assert.ok(r.A.condHours>0);assert.ok(r.A.dampHours>=r.A.condHours)});
test('humidity correction is clamped at 1 and 100',()=>{const s={u:2.7,rsi:.13,delta:-40};let r=E.evaluateSlot({inside:20,outside:0,rh:20},s);assert.equal(r.rh,1);s.delta=30;r=E.evaluateSlot({inside:20,outside:0,rh:90},s);assert.equal(r.rh,100)});
test('JSON copy roundtrip remains equal to normalized state',()=>{const s=base();assert.deepEqual(E.normalize(JSON.parse(JSON.stringify(s))),E.normalize(s))});
test('CSV roundtrip restores exactly source rows',()=>{const s=base();const csv=E.reportCSV(E.analyze(s));assert.deepEqual(E.parseCsvRows('\ufeff'+csv),s.rows)});
test('CSV header and time errors are rejected',()=>{assert.throws(()=>E.parseCsvRows('x,y'),/12行/);const s=base();const csv=E.reportCSV(E.analyze(s)).replace('02:00,','03:00,');assert.throws(()=>E.parseCsvRows(csv),/時刻が不一致/)});
test('CSV includes all twelve records and no formulas',()=>{const csv=E.reportCSV(E.analyze(base()));assert.equal(csv.trim().split(/\r?\n/).length,13);assert.ok(csv.startsWith('time,outside_C'))});
test('bad scenario input rejected',()=>{const s=base();s.B.u=0;assert.throws(()=>E.analyze(s),/U値/);s.B.u=7;assert.throws(()=>E.analyze(s),/U値/)});
test('malformed record length rejected',()=>{const s=base();s.rows.pop();assert.throws(()=>E.analyze(s),/12件/)});
test('bad room humidity and nonnumeric strings rejected',()=>{const s=base();s.rows[0].rh=101;assert.throws(()=>E.analyze(s),/湿度/);s.rows[0].rh='hi';assert.throws(()=>E.analyze(s),/湿度/)});
test('strange data shapes rejected safely',()=>{assert.throws(()=>E.normalize(null));assert.throws(()=>E.normalize({rows:'broken'}));});
test('each slot representative of two hours',()=>{const r=E.analyze(base());near(r.A.dampHours,2*r.A.slots.filter(x=>x.damp).length);near(r.B.condHours,2*r.B.slots.filter(x=>x.condense).length)});
test('randomized comparison invariants (700 cases)',()=>{
 let seed=3245619;const random=()=>{seed=(1664525*seed+1013904223)>>>0;return seed/4294967296};
 for(let i=0;i<700;i++){
   const indoor=14+random()*15,outside=-20+random()*25,rh=20+random()*70;
   const u=.6+random()*5.8;
   const s={u,rsi:.13+random()*.10,delta:-10+random()*15};
   const row={inside:indoor,outside,rh};
   const x=E.evaluateSlot(row,s);
   assert.ok(Number.isFinite(x.surfaceRH)&&Number.isFinite(x.margin));
   assert.ok(x.ts<=indoor&&x.ts>=outside);
   near(x.safeRH100/x.safeRH80,1.25,1e-10);
   assert.equal(x.condense,x.damp&&x.surfaceRH>=100-1e-10);
   const lower=E.evaluateSlot(row,{...s,u:.6});
   assert.ok(lower.ts>=x.ts-1e-9);
   assert.ok(lower.surfaceRH<=x.surfaceRH+1e-8);
 }
});
