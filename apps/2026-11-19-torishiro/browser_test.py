"""Playwright interactive MVP smoke tests. Uses original source via set_content if file navigation blocked."""
from pathlib import Path
from playwright.sync_api import sync_playwright
import json
BASE = Path(__file__).resolve().parent
checks=[]
def check(desc, okay):
    checks.append((desc, bool(okay)))
    if not okay: raise AssertionError(desc)
def boot(page):
    html=(BASE/'index.html').read_text(encoding='utf-8')
    page.set_content(html.replace('<link rel="stylesheet" href="style.css">','').replace('<script src="engine.js"></script>','').replace('<script src="app.js"></script>',''),wait_until='domcontentloaded')
    page.add_style_tag(content=(BASE/'style.css').read_text(encoding='utf-8'))
    # file:// is blocked by current browser management policy; simulate Web Storage for about:blank.
    page.evaluate("""() => { const data={}; Object.defineProperty(window,'localStorage',{configurable:true,value:{getItem(k){return data[k]??null},setItem(k,v){data[k]=String(v)},removeItem(k){delete data[k]}}}); }""")
    page.add_script_tag(content=(BASE/'engine.js').read_text(encoding='utf-8'))
    page.add_script_tag(content=(BASE/'app.js').read_text(encoding='utf-8'))

with sync_playwright() as pw:
    browser=pw.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
    context=browser.new_context(viewport={'width':1440,'height':900},accept_downloads=True,device_scale_factor=1)
    page=context.new_page(); errors=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    try:
        page.goto((BASE/'index.html').as_uri(),timeout=3500)
        direct='succeeded'
    except Exception as e:
        direct='blocked ('+str(e).splitlines()[0][:100]+')'
    page.close()
    page=context.new_page()
    page.on('pageerror',lambda e:errors.append(str(e)))
    boot(page)
    check('initial app ready',page.locator('#summary-chip').inner_text()=='3条件をクリア')
    check('initial subject fits',page.locator('#state-subject').inner_text()=='収まる')
    check('initial backdrop fits',page.locator('#state-backdrop').inner_text()=='端が写らない')
    check('initial room fits',page.locator('#state-room').inner_text()=='収まる')
    check('front SVG visible',page.locator('#front-diagram svg').count()==1)
    check('top SVG visible',page.locator('#top-diagram svg').count()==1)
    check('lens alternatives count',page.locator('#lens-rows tr').count()==9)
    check('default lens 50 mm',page.locator('#focal').input_value()=='50')
    check('default field metrics', '102.6' in page.locator('#metric-front').inner_text())
    page.locator('#subjectW').fill('300')
    check('subject overflow detected',page.locator('#state-subject').inner_text()=='見切れる')
    check('warning display',page.locator('#summary-chip').inner_text()=='調整が必要')
    page.locator('#subjectW').fill('40')
    check('subject restored',page.locator('#state-subject').inner_text()=='収まる')
    page.locator('#backdropW').fill('40')
    check('background edge detected',page.locator('#state-backdrop').inner_text()=='端が写る')
    page.locator('#backdropW').fill('180')
    check('background restored',page.locator('#state-backdrop').inner_text()=='端が写らない')
    page.locator('#roomDepth').fill('180')
    check('room insufficient',page.locator('#state-room').inner_text()=='長さ不足')
    page.locator('#roomDepth').fill('290')
    check('room restored',page.locator('#state-room').inner_text()=='収まる')
    page.locator('#orientation').select_option('portrait')
    check('portrait metric changed','68.4' in page.locator('#metric-front').inner_text())
    page.locator('#orientation').select_option('landscape')
    page.locator('[data-focal="35"]').click()
    check('select alternative updates input',page.locator('#focal').input_value()=='35')
    check('highlight alternative row',page.locator('#lens-rows tr.active').count()==1)
    page.locator('#focal').fill('50')
    with page.expect_download() as d:page.locator('#save-json').click()
    js=d.value
    check('JSON output filename',js.suggested_filename=='torishiro-settings.json')
    savepath=BASE/'test-export.json';js.save_as(savepath)
    obj=json.loads(savepath.read_text(encoding='utf-8'))
    check('JSON output valid',obj['app']=='torishiro' and obj['settings']['focal']==50)
    with page.expect_download() as d:page.locator('#save-csv').click()
    csv=d.value;check('CSV output filename',csv.suggested_filename=='torishiro-result.csv')
    csv.save_as(BASE/'test-export.csv');check('CSV BOM and content',(BASE/'test-export.csv').read_bytes().startswith(b'\xef\xbb\xbf') and '背景紙'.encode() in (BASE/'test-export.csv').read_bytes())
    with page.expect_download() as d:page.locator('#save-svg').click()
    svg=d.value;check('SVG output filename',svg.suggested_filename=='torishiro-view.svg')
    svg.save_as(BASE/'test-export.svg');check('SVG valid element','<svg' in (BASE/'test-export.svg').read_text(encoding='utf-8'))
    page.locator('#focal').fill('85')
    page.locator('#import-file').set_input_files(str(savepath))
    page.wait_for_function("document.getElementById('focal').value==='50'",timeout=3000);check('JSON import restores focal',page.locator('#focal').input_value()=='50')
    page.locator('#import-file').set_input_files({'name':'invalid.json','mimeType':'application/json','buffer':b'{bad'})
    page.locator('#notice').filter(has_text='読み込み失敗').wait_for(timeout=3000);check('bad JSON rejected',page.locator('#notice').inner_text().startswith('読み込み失敗'))
    check('bad JSON does not clear state',page.locator('#focal').input_value()=='50')
    page.locator('#title').fill('<img src=x onerror=alert(1)>')
    check('title does not create HTML',page.locator('img[src=x]').count()==0)
    page.locator('#reset').click()
    check('reset works',page.locator('#title').input_value()=='陶器のオンライン販売写真')
    check('reset success status',page.locator('#summary-chip').inner_text()=='3条件をクリア')
    check('no JS page exceptions',len(errors)==0)
    page.screenshot(path=str(BASE/'desktop.png'),full_page=True)
    mobile=browser.new_context(viewport={'width':390,'height':844},device_scale_factor=1,accept_downloads=True)
    mob=mobile.new_page();boot(mob)
    check('mobile initial status',mob.locator('#summary-chip').inner_text()=='3条件をクリア')
    check('mobile no viewport horizontal overflow',mob.evaluate('document.documentElement.scrollWidth <= window.innerWidth + 2'))
    mob.locator('#focal').fill('70')
    check('mobile editing responsive',mob.locator('#focal').input_value()=='70')
    check('mobile preview visible',mob.locator('#front-diagram svg').count()==1)
    mob.screenshot(path=str(BASE/'mobile.png'),full_page=True)
    # Relate engine and browser values to avoid stale JavaScript.
    check('runtime field calculation verified',abs(page.evaluate('TORISHIRO.calculate(TORISHIRO.DEFAULTS).field.width')-108)<.00001)
    for f in ['test-export.json','test-export.csv','test-export.svg']:(BASE/f).unlink(missing_ok=True)
    print('Browser direct file navigation: '+direct)
    print(f'Chromium interactions: {sum(x[1] for x in checks)}/{len(checks)} passed')
    browser.close()